#!/usr/bin/env bash
# Host-side prerequisites for cross-compiling from the wails3-dev box.
#
#   ./host-setup.sh
#
# Idempotent. Installs, for the current user (no sudo needed):
#   * ~/.config/containers/wails3-dev-containers.conf
#       a containers.conf fragment with userns=keep-id and label=false
#   * ~/.config/systemd/user/podman.service.d/wails3-dev-containers.conf
#       makes the rootless podman API socket use that fragment
#   * enables and restarts podman.socket, so /run/user/<uid>/podman/podman.sock
#       exists at login
#
# Why: the box has no container engine of its own; its docker CLI talks to this
# socket. Wails' cross-compilation taskfiles bind-mount $HOME paths into
# wails-cross and then chown the output back to your uid, which only behaves
# under keep-id + disabled SELinux labelling. Details in the config file and in
# README.md, "Cross-compilation".
set -euo pipefail

here=$(cd -- "$(dirname -- "$0")" && pwd)
confdir="${XDG_CONFIG_HOME:-$HOME/.config}"
conf="$confdir/containers/wails3-dev-containers.conf"
dropin="$confdir/systemd/user/podman.service.d/wails3-dev-containers.conf"

install -d "$confdir/containers" "$confdir/systemd/user/podman.service.d"
install -m 0644 "$here/containers-wails3-dev.conf" "$conf"

printf '# Generated by wails3-dev-distrobox/host-setup.sh\n[Service]\nEnvironment=CONTAINERS_CONF=%s\n' \
  "$conf" > "$dropin"
chmod 0644 "$dropin"

systemctl --user daemon-reload
systemctl --user enable --now podman.socket
systemctl --user restart podman.socket

if [[ "$(loginctl show-user "$USER" -p Linger --value 2>/dev/null)" != "yes" ]]; then
  echo "note: lingering is off for $USER; run 'loginctl enable-linger $USER' so the socket" >&2
  echo "      exists when you are not logged in." >&2
fi

sleep 1
echo "podman.socket: $(systemctl --user is-active podman.socket) ($(systemctl --user is-enabled podman.socket))"
echo "socket:        ${XDG_RUNTIME_DIR:-/run/user/$(id -u)}/podman/podman.sock"
echo
echo "Verify from inside the box:"
echo "  distrobox enter wails3-dev --clean-path -- bash -lc 'docker info && wails3 doctor'"
